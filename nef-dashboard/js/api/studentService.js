const studentService = {
  async getStudents() {
    if (window.CONFIG.USE_MOCK_API) {
      let students = JSON.parse(localStorage.getItem("nef_students")) || [];
      let updated = false;
      students = students.map(s => {
        if (s.residencyStatus === "Resident") {
          s.residencyStatus = "Permanent";
          updated = true;
        }
        return s;
      });
      if (updated) localStorage.setItem("nef_students", JSON.stringify(students));
      return students;
    }
    return await window.httpClient.get("/students");
  },
  // PUT /students - grade promotion only (class / result / passOutDate).
  async saveStudents(students) {
    if (window.CONFIG.USE_MOCK_API) {
      const all = await this.getStudents();
      const byId = new Map(students.map(s => [s.studentId, s]));
      const merged = all.map(s => byId.has(s.studentId)
        ? { ...s, class: byId.get(s.studentId).class, result: byId.get(s.studentId).result, passOutDate: byId.get(s.studentId).passOutDate }
        : s);
      localStorage.setItem("nef_students", JSON.stringify(merged));
      return merged;
    }
    const payload = students.map(s => ({
      studentId: s.studentId,
      class: s.class,
      result: s.result || "",
      passOutDate: s.passOutDate || ""
    }));
    return await window.httpClient.put("/students", payload);
  },
  // POST /students - enrollment. `studentData.guardian` (optional) creates the
  // guardian in the same server transaction. Ids are generated by the server.
  async createStudent(studentData) {
    if (window.CONFIG.USE_MOCK_API) {
      const students = await this.getStudents();
      const { guardian, ...student } = studentData;
      const created = { studentId: mockNextId(students, "studentId", "STD"), ...student };
      if (guardian) {
        const guardians = await this.getGuardians();
        created.guardianId = mockNextId(guardians, "guardianId", "GRD");
        guardians.push({ guardianId: created.guardianId, ...guardian });
        localStorage.setItem("nef_guardians", JSON.stringify(guardians));
      }
      students.push(created);
      localStorage.setItem("nef_students", JSON.stringify(students));
      const schools = JSON.parse(localStorage.getItem("nef_schools")) || [];
      const sch = schools.find(s => s.name === created.schoolName);
      if (sch) { sch.totalStudents = (sch.totalStudents || 0) + 1; localStorage.setItem("nef_schools", JSON.stringify(schools)); }
      return created;
    }
    return await window.httpClient.post("/students", studentData);
  },
  // PUT /students/:id - one student.
  async updateStudent(studentId, studentData) {
    if (window.CONFIG.USE_MOCK_API) {
      const students = await this.getStudents();
      const idx = students.findIndex(s => s.studentId === studentId);
      if (idx !== -1) {
        students[idx] = { ...students[idx], ...studentData };
        localStorage.setItem("nef_students", JSON.stringify(students));
        return students[idx];
      }
      return studentData;
    }
    return await window.httpClient.put(`/students/${encodeURIComponent(studentId)}`, studentData);
  },
  async getGuardians() {
    if (window.CONFIG.USE_MOCK_API) {
      return JSON.parse(localStorage.getItem("nef_guardians")) || [];
    }
    return await window.httpClient.get("/guardians");
  },
  // PUT /guardians/:id - one guardian.
  async updateGuardian(guardianId, guardianData) {
    if (window.CONFIG.USE_MOCK_API) {
      const guardians = await this.getGuardians();
      const idx = guardians.findIndex(g => g.guardianId === guardianId);
      if (idx !== -1) {
        guardians[idx] = { ...guardians[idx], ...guardianData };
        localStorage.setItem("nef_guardians", JSON.stringify(guardians));
        return guardians[idx];
      }
      return guardianData;
    }
    return await window.httpClient.put(`/guardians/${encodeURIComponent(guardianId)}`, guardianData);
  },
  async deleteStudent(studentId) {
    if (window.CONFIG.USE_MOCK_API) {
      const students = await this.getStudents();
      const student = students.find(s => s.studentId === studentId);
      const remaining = students.filter(s => s.studentId !== studentId);
      localStorage.setItem("nef_students", JSON.stringify(remaining));
      if (student && student.guardianId && !remaining.some(s => s.guardianId === student.guardianId)) {
        const guardians = await this.getGuardians();
        localStorage.setItem("nef_guardians", JSON.stringify(guardians.filter(g => g.guardianId !== student.guardianId)));
      }
      const attendance = await window.attendanceService.getAttendance();
      await window.attendanceService.saveAttendance(attendance.filter(a => a.studentId !== studentId));
      return { message: "Student record deleted successfully." };
    }
    return await window.httpClient.delete(`/students/${encodeURIComponent(studentId)}`);
  }
};
window.studentService = studentService;
